#!/usr/bin/env python3
"""Generate a deterministic Lua production contract for a Factorio scenario."""

from __future__ import annotations

import argparse
import copy
import math
import json
from pathlib import Path
import re
import subprocess
import sys
from typing import Any


REPOSITORY = Path(__file__).resolve().parents[1]
ANALYZER = REPOSITORY / "tools" / "analyze_factorio_prereqs.py"
IDENTIFIER = re.compile(r"^[A-Za-z_][A-Za-z0-9_]*$")


def parse_arguments() -> argparse.Namespace:
    parser = argparse.ArgumentParser(
        description="Generate a Lua scenario manifest from resolved Factorio prototypes."
    )
    parser.add_argument("args_file", type=Path)
    parser.add_argument("output", type=Path)
    parser.add_argument("--check", action="store_true")
    parser.add_argument("--stages", type=Path, help="bounded campaign configuration")
    parser.add_argument("--timeout-seconds", type=int, default=300)
    return parser.parse_args()


def lua(value: Any, indent: int = 0) -> str:
    if value is None:
        return "nil"
    if value is True:
        return "true"
    if value is False:
        return "false"
    if isinstance(value, (int, float)):
        return repr(value)
    if isinstance(value, str):
        return json.dumps(value, ensure_ascii=False)
    prefix = "  " * indent
    child = "  " * (indent + 1)
    if isinstance(value, list):
        if not value:
            return "{}"
        entries = [f"{child}{lua(entry, indent + 1)}," for entry in value]
        return "{\n" + "\n".join(entries) + f"\n{prefix}}}"
    if isinstance(value, dict):
        if not value:
            return "{}"
        entries = []
        for key in sorted(value):
            rendered_key = key if IDENTIFIER.match(key) else f"[{lua(key)}]"
            entries.append(
                f"{child}{rendered_key} = {lua(value[key], indent + 1)},"
            )
        return "{\n" + "\n".join(entries) + f"\n{prefix}}}"
    raise TypeError(f"unsupported manifest value: {type(value).__name__}")


def compact_step(step: dict[str, Any]) -> dict[str, Any]:
    fields = (
        "cycles",
        "executor",
        "fuel",
        "heat",
        "ingredients",
        "outputs",
        "producer",
        "product",
        "spoil_ticks",
        "ticks_per_cycle",
        "total_ticks_single_executor",
    )
    return {field: step[field] for field in fields if field in step}


def load_contract(args_file: Path, timeout_seconds: int) -> dict[str, Any]:
    args_path = args_file.resolve()
    try:
        display_args = args_path.relative_to(REPOSITORY)
    except ValueError:
        display_args = args_path
    completed = subprocess.run(
        [sys.executable, str(ANALYZER), f"@{display_args}", "--json"],
        cwd=REPOSITORY,
        text=True,
        stdout=subprocess.PIPE,
        stderr=subprocess.PIPE,
        timeout=timeout_seconds,
        check=False,
    )
    if completed.returncode != 0:
        detail = completed.stderr.strip() or completed.stdout.strip()
        raise RuntimeError(
            f"prerequisite analysis exited {completed.returncode}: {detail}"
        )
    report = json.loads(completed.stdout)
    manifest = report.get("production_manifest")
    if not isinstance(manifest, dict):
        raise RuntimeError("prerequisite report has no production manifest")
    if report.get("unresolved"):
        raise RuntimeError(f"manifest contains unresolved products: {report['unresolved']}")
    if report.get("required_technologies"):
        raise RuntimeError(
            "manifest requires undeclared technologies: "
            f"{report['required_technologies']}"
        )
    if manifest.get("available_inputs"):
        raise RuntimeError(
            "manifest requires undeclared consumable available inputs: "
            f"{manifest['available_inputs']}"
        )
    contract = {
        "schema": 1,
        "assumed_technologies": report["assumed_technologies"],
        "fuel_consumption": manifest["fuel_consumption"],
        "initial_stock": manifest["initial_stock"],
        "raw_inputs": manifest["raw_inputs"],
        "steps": [compact_step(step) for step in reversed(manifest["steps"])],
        "surplus": manifest["surplus"],
        "targets": manifest["targets"],
        "executor_stock": {
            name: max(0, 1 - manifest["targets"].get(name, 0))
            for name in {step.get("provider") for step in report["selected_recipes"]}
            if name and not name.startswith("<") and manifest["targets"].get(name, 0) < 1
        },
    }
    return contract


def generate(args_file: Path, timeout_seconds: int) -> str:
    contract = load_contract(args_file, timeout_seconds)
    display_args = args_file.resolve()
    if display_args.is_relative_to(REPOSITORY):
        display_args = display_args.relative_to(REPOSITORY)
    return (
        f"-- Generated by tools/generate_factorio_scenario_manifest.py\n"
        f"-- Source: {display_args}\n"
        f"return {lua(contract)}\n"
    )


def add_amount(values, name, amount):
    values[name] = values.get(name, 0) + amount
    if abs(values[name]) < 1e-7:
        del values[name]


def split_contract(contract, config):
    """Return independent native-crafting stages with conserved boundary stock."""
    ledger = dict(contract["raw_inputs"])
    for name, amount in contract["initial_stock"].items():
        add_amount(ledger, name, amount)
    remaining = [step["cycles"] for step in contract["steps"]]
    stages = []
    stage = None
    elapsed = 0
    previous_index = None
    budget = config["batch_ticks"]
    if not 0 < budget <= 24000:
        raise ValueError("batch_ticks must be in 1..24000")
    fixtures = config["fixture"]
    while any(remaining):
        selected = None
        for index, step in enumerate(contract["steps"]):
            if not remaining[index]:
                continue
            executor = step.get("executor")
            if step.get("spoil_ticks"):
                copies = remaining[index]
            elif executor["kind"] == "character":
                copies = 1
            else:
                copies = min(config["parallelism"], fixtures.get(executor["item"], 0) +
                             int(ledger.get(executor["item"], 0)))
            if copies < 1:
                continue
            required = {}
            for ingredient in step["ingredients"]:
                add_amount(required, ingredient["name"], ingredient["amount"] / step["cycles"])
            if step.get("fuel"):
                add_amount(required, step["fuel"]["name"], step["fuel"]["amount_per_cycle"])
            count = min(copies, remaining[index])
            for name, amount in required.items():
                count = min(count, math.floor((ledger.get(name, 0) + 1e-7) / amount))
            if step.get("spoil_ticks") and count != remaining[index]:
                continue
            if count:
                selected = index, step, required, count
                break
        if selected is None:
            raise ValueError("campaign has no executable batch at its declared stock boundary")
        index, step, required, count = selected
        duration = math.ceil(step.get("spoil_ticks") or step["ticks_per_cycle"]) + 120
        if duration > budget:
            raise ValueError(f"single cycle exceeds batch budget: {step['producer']}")
        if stage is None or elapsed + duration > budget:
            if stage is not None:
                stage["targets"] = dict(ledger)
                stage["deadline"] = math.ceil((elapsed * 1.2 + 600) / 60) * 60
            stage = dict(schema=1, assumed_technologies=contract["assumed_technologies"],
                         initial_stock=dict(ledger), raw_inputs={}, steps=[],
                         surplus={}, targets={}, fuel_consumption={})
            stages.append(stage)
            elapsed = 0
            previous_index = None
        for name, amount in required.items():
            add_amount(ledger, name, -amount * count)
        for output in step["outputs"]:
            add_amount(ledger, output["name"], output["amount"] * count / step["cycles"])
        if step.get("fuel"):
            add_amount(stage["fuel_consumption"], step["fuel"]["name"],
                       step["fuel"]["amount_per_cycle"] * count)
        batch = copy.deepcopy(step)
        batch["cycles"] = count
        if batch.get("fuel"):
            batch["fuel"]["total_amount"] = batch["fuel"]["amount_per_cycle"] * count
        batch["total_ticks_single_executor"] = step.get("spoil_ticks") or step["ticks_per_cycle"] * count
        for field in ("ingredients", "outputs"):
            for row in batch[field]:
                row["amount"] *= count / step["cycles"]
                if abs(row["amount"] - round(row["amount"])) < 1e-7:
                    row["amount"] = round(row["amount"])
        # Keep batch order: this also preserves each self-powered fuel prime.
        if previous_index == index and not step.get("spoil_ticks"):
            previous = stage["steps"][-1]
            previous["cycles"] += count
            previous["total_ticks_single_executor"] += batch["total_ticks_single_executor"]
            for field in ("ingredients", "outputs"):
                for old, new in zip(previous[field], batch[field]):
                    old["amount"] += new["amount"]
            if previous.get("fuel"):
                previous["fuel"]["total_amount"] += batch["fuel"]["total_amount"]
        else:
            stage["steps"].append(batch)
        previous_index = index
        remaining[index] -= count
        elapsed += duration
    stage["targets"] = dict(ledger)
    stage["deadline"] = math.ceil((elapsed * 1.2 + 600) / 60) * 60
    expected = dict(contract["targets"])
    for source in (contract["surplus"], contract.get("executor_stock", {})):
        for name, amount in source.items():
            add_amount(expected, name, amount)
    for name in ledger.keys() | expected.keys():
        if not math.isclose(ledger.get(name, 0), expected.get(name, 0), abs_tol=1e-6):
            raise ValueError(f"stage boundary does not conserve {name}")
    fuel = {}
    for stage in stages:
        for name, amount in stage["fuel_consumption"].items():
            add_amount(fuel, name, amount)
    for name in fuel.keys() | contract["fuel_consumption"].keys():
        if not math.isclose(fuel.get(name, 0), contract["fuel_consumption"].get(name, 0), abs_tol=1e-6):
            raise ValueError(f"stage fuel does not conserve {name}")
    return stages


def write_stages(contract, config, output, check):
    stages = split_contract(contract, config)
    index_path = output / config["case"] / "stages.json"
    previous = json.loads(index_path.read_text()) if index_path.is_file() else []
    used = set()
    names = []
    for index, stage in enumerate(stages):
        name = config["case"] if index == 0 else config["case"] + "-" + stage["steps"][0]["producer"].removeprefix("nullius-")
        name = re.sub(r"[^a-z0-9-]+", "-", name).strip("-")
        base = name
        suffix = 2
        while name in used:
            name = f"{base}-{suffix}"
            suffix += 1
        used.add(name)
        names.append(name)
        directory = output / name
        runner = dict(case=name, contract=None, deadline=stage["deadline"],
                      parallelism=config["parallelism"], fixture=config["fixture"],
                      scripted_heat=True, ordered_steps=True)
        control = "local config = " + lua(runner) + '\n'
        control += 'config.contract = require("manifest")\n'
        control += 'require("__nullius-star__/scenarios/vulcanus-manifest-runner")(config)\n'
        files = {"control.lua": control,
                 "manifest.lua": "-- Generated bounded campaign stock contract.\nreturn " + lua(stage) + "\n",
                 "test.json": json.dumps({"schema": 1, "until_tick": stage["deadline"] + 30}) + "\n"}
        for filename, contents in files.items():
            path = directory / filename
            if check:
                if not path.is_file() or path.read_text() != contents:
                    raise RuntimeError(f"generated stage is stale: {path}")
            else:
                directory.mkdir(parents=True, exist_ok=True)
                path.write_text(contents)
    obsolete = set(previous) - used
    if check:
        if previous != names:
            raise RuntimeError(f"generated stage index is stale: {index_path}")
    else:
        for name in obsolete:
            if not name.startswith(config["case"] + "-") or Path(name).name != name:
                raise ValueError(f"invalid obsolete stage name: {name}")
            directory = output / name
            for filename in ("control.lua", "manifest.lua", "test.json"):
                (directory / filename).unlink()
            directory.rmdir()
        index_path.write_text(json.dumps(names, indent=2) + "\n")
    print(f"{config['case']}: {len(stages)} conserved stages")


def main() -> int:
    args = parse_arguments()
    try:
        if args.stages:
            config = json.loads(args.stages.read_text())
            contract = load_contract(args.args_file, args.timeout_seconds)
            write_stages(contract, config, args.output, args.check)
            return 0
        rendered = generate(args.args_file, args.timeout_seconds)
        output = args.output.resolve()
        if args.check:
            if not output.is_file() or output.read_text(encoding="utf-8") != rendered:
                print(f"generated manifest is stale: {output}", file=sys.stderr)
                return 1
            return 0
        output.parent.mkdir(parents=True, exist_ok=True)
        output.write_text(rendered, encoding="utf-8")
        return 0
    except (OSError, ValueError, RuntimeError, subprocess.TimeoutExpired) as error:
        print(f"ERROR: {error}", file=sys.stderr)
        return 2


if __name__ == "__main__":
    raise SystemExit(main())
