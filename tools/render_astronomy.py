#!/usr/bin/env python3
"""Build astronomy models and publish calibrated Factorio sprites."""

import argparse
from concurrent.futures import ThreadPoolExecutor
import hashlib
import json
import math
import os
from pathlib import Path
import shutil
import subprocess
import tempfile
import time
from PIL import Image, ImageDraw

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "release/astronomy"
DEST = ROOT / "nullius-star/graphics/entity/astronomy"
ICONS = ROOT / "nullius-star/graphics/icons/astronomy"
MOTION_PATH = ROOT / "art/astronomy/motion.json"
MOTIONS = json.loads(MOTION_PATH.read_text())
MODELS = {
    "nullius-radio-dish": "radio-dish",
    "nullius-radio-dish-pneumatic": "pneumatic-radio-dish",
    "nullius-correlator": "correlator",
}


def motion_name(model):
    return "correlator-fans" if model == "correlator" else "reflector"


def load_pass(variant, kind, frame=0):
    suffix = f"-frame-{frame:02d}" if frame else ""
    im = Image.open(OUT / f"{variant}{suffix}-{kind}.png").convert("RGBA")
    if kind == "glow":
        pixels = []
        for r, g, b, coverage in im.getdata():
            r, g, b = (round(c * coverage / 255) for c in (r, g, b))
            alpha = max(r, g, b)
            pixels.append(
                (
                    round(r * 255 / alpha),
                    round(g * 255 / alpha),
                    round(b * 255 / alpha),
                    alpha,
                )
                if alpha
                else (0, 0, 0, 0)
            )
        im.putdata(pixels)
    elif kind == "shadow":
        alpha = im.getchannel("A").point(lambda a: round(max(0, a - 8) * 255 / 247))
        im = Image.new("RGBA", im.size)
        im.putalpha(alpha)
    return im


def publish():
    metadata = json.loads((OUT / "render.json").read_text())
    DEST.mkdir(parents=True, exist_ok=True)
    ICONS.mkdir(parents=True, exist_ok=True)
    scale = 32 / metadata["pixels_per_tile"]
    origin = metadata["origin"]
    lua = ["-- Generated by tools/render_astronomy.py.", "return {"]
    sheet = Image.new("RGBA", (1200, 630), (49, 53, 54, 255))
    draw = ImageDraw.Draw(sheet)
    hashes = {}

    def sprite(variant, kind, frames, speed, repeat=1):
        boxes = [im.getchannel("A").getbbox() for im in frames]
        if any(box is None for box in boxes):
            raise ValueError(f"Empty {variant} {kind} frame")
        bounds = (
            min(b[0] for b in boxes),
            min(b[1] for b in boxes),
            max(b[2] for b in boxes),
            max(b[3] for b in boxes),
        )
        if (
            bounds[0] == 0
            or bounds[1] == 0
            or bounds[2] == frames[0].width
            or bounds[3] == frames[0].height
        ):
            raise ValueError(f"Clipped {variant} {kind}")
        bounds = (bounds[0] - 2, bounds[1] - 2, bounds[2] + 2, bounds[3] + 2)
        width, height = bounds[2] - bounds[0], bounds[3] - bounds[1]
        columns = min(4, len(frames))
        atlas = Image.new(
            "RGBA", (width * columns, height * math.ceil(len(frames) / columns))
        )
        for index, im in enumerate(frames):
            atlas.paste(
                im.crop(bounds),
                ((index % columns) * width, (index // columns) * height),
            )
        filename = f"{variant}-{kind}.png"
        atlas.save(DEST / filename)
        hashes[str((DEST / filename).relative_to(ROOT))] = hashlib.sha256(
            (DEST / filename).read_bytes()
        ).hexdigest()
        shift = [
            ((bounds[i] + bounds[i + 2]) / 2 - origin[i]) * scale for i in range(2)
        ]
        flags = ",draw_as_shadow=true" if kind == "shadow" else ""
        if kind == "glow":
            flags = ',draw_as_glow=true,blend_mode="additive"'
        return (
            '{filename="__nullius-star__/graphics/entity/astronomy/'
            + filename
            + '",'
            + f"width={width},height={height},scale={scale},shift=util.by_pixel({shift[0]},{shift[1]}),"
            + f"frame_count={len(frames)},line_length={columns},repeat_count={repeat},animation_speed={speed}"
            + flags
            + "}"
        )

    motion_layers = {}
    motion_stills = {}
    for name, motion in MOTIONS.items():
        motion_layers[name] = []
        motion_stills[name] = {}
        for kind in ("body",):
            frames = [load_pass(name, kind, frame) for frame in range(motion["frames"])]
            motion_stills[name][kind] = frames[0]
            motion_layers[name].append(sprite(name, kind, frames, motion["speed"]))

    for column, (entity, model) in enumerate(MODELS.items()):
        name = motion_name(model)
        motion = MOTIONS[name]
        lua.append('  ["' + entity + '"] = {')
        lua.append(
            '    icon = "__nullius-star__/graphics/icons/astronomy/' + model + '.png",'
        )
        lua.append("    animation = {")
        directions = (
            ("north",) if model == "correlator" else ("north", "east", "south", "west")
        )
        glows = {}
        for direction in directions:
            variant = model if direction == "north" else model + "-" + direction
            lua.append(f"      {direction} = {{layers={{")
            bodies = {}
            for kind in ("body", "shadow"):
                im = load_pass(variant, kind)
                lua.append(
                    "        "
                    + sprite(variant, kind, [im], motion["speed"], motion["frames"])
                    + ","
                )
                bodies[kind] = (
                    Image.alpha_composite(im, motion_stills[name][kind])
                    if kind == "body"
                    else im
                )
            lua.extend("        " + entry + "," for entry in motion_layers[name])
            lua.append("      }},")
            glow = load_pass(variant, "glow")
            frames = []
            for frame in range(32):
                strength = 0.8 + 0.2 * math.cos(math.tau * frame / 32)
                cell = glow.copy()
                cell.putalpha(glow.getchannel("A").point(lambda a: round(a * strength)))
                frames.append(cell)
            glows[direction] = sprite(variant, "glow", frames, 0.2)
            if direction == "north":
                north_bodies = bodies
        lua.append("    },\n    working_visualisations = {{constant_speed=true,")
        for direction, glow in glows.items():
            field = "animation" if model == "correlator" else direction + "_animation"
            lua.append(f"      {field}={glow},")
        shift = "{0,1.9}" if model == "correlator" else "{-1.25,1.45}"
        color = "{0.5,0.8,1}" if model == "correlator" else "{1,0.65,0.3}"
        lua.append(
            "    }, {light={intensity=0.16,size=2.5,minimum_darkness=0.3,"
            + f"shift={shift},color={color}"
            + "}}},\n  },"
        )
        bodies = north_bodies
        composite = Image.new("RGBA", (metadata["canvas"], metadata["canvas"]))
        icon = bodies["body"].crop(bodies["body"].getchannel("A").getbbox())
        icon.thumbnail((120, 120), Image.Resampling.LANCZOS)
        icon_canvas = Image.new("RGBA", (128, 128))
        icon_canvas.alpha_composite(
            icon, ((128 - icon.width) // 2, (128 - icon.height) // 2)
        )
        icon_canvas.save(ICONS / (model + ".png"))
        hashes[str((ICONS / (model + ".png")).relative_to(ROOT))] = hashlib.sha256(
            (ICONS / (model + ".png")).read_bytes()
        ).hexdigest()
        composite.alpha_composite(bodies["shadow"])
        composite.alpha_composite(bodies["body"])
        # The checker grid has the same tile projection as the game.
        for x in range(column * 400, column * 400 + 400, 32):
            draw.line((x, 50, x, 580), fill=(65, 70, 69), width=1)
        for y in range(50, 581, 32):
            draw.line(
                (column * 400, y, column * 400 + 399, y), fill=(65, 70, 69), width=1
            )
        composite = composite.resize((384, 384), Image.Resampling.LANCZOS)
        sheet.alpha_composite(composite, (column * 400 + 8, 80))
        draw.text((column * 400 + 16, 20), model.upper(), fill=(225, 220, 195))
        draw.text(
            (column * 400 + 16, 485),
            "5 x 5 tiles | 32 px/tile preview",
            fill=(200, 205, 200),
        )
        detail = bodies["body"].crop(bodies["body"].getchannel("A").getbbox())
        detail.thumbnail((360, 440), Image.Resampling.LANCZOS)
        # Save a larger native-resolution inspection view as well.
        bg = Image.new("RGBA", (420, 500), (49, 53, 54, 255))
        bg.alpha_composite(detail, ((420 - detail.width) // 2, 20))
        bg.save(OUT / (model + "-preview.png"))
    lua.append("}")
    (ROOT / "nullius-star/prototypes/entity/astronomy-graphics.lua").write_text(
        "\n".join(lua) + "\n"
    )
    sheet.convert("RGB").save(OUT / "preview.png")
    sheet.convert("RGB").save(ROOT / "art/astronomy/rendered/preview.png")
    metadata["sprite_sha256"] = hashes
    metadata["source_sha256"] = {
        str(p.relative_to(ROOT)): hashlib.sha256(p.read_bytes()).hexdigest()
        for p in (ROOT / "art/astronomy/build.py", Path(__file__), MOTION_PATH)
    }
    (OUT / "manifest.json").write_text(json.dumps(metadata, indent=2) + "\n")
    (ROOT / "art/astronomy/rendered/manifest.json").write_text(
        json.dumps(metadata, indent=2) + "\n"
    )
    print("Rendered", len(MODELS), "models; preview:", OUT / "preview.png")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--blender", default="blender")
    parser.add_argument("--jobs", type=int, help="Concurrent Blender scene processes")
    parser.add_argument("--threads", type=int, help="CPU threads per Blender process")
    args = parser.parse_args()
    if args.jobs is not None and args.jobs < 1:
        parser.error("--jobs must be positive")
    if args.threads is not None and args.threads < 1:
        parser.error("--threads must be positive")
    OUT.mkdir(parents=True, exist_ok=True)
    views = [
        model + suffix
        for model in MODELS.values()
        for suffix in (
            ("",) if model == "correlator" else ("", "-east", "-south", "-west")
        )
    ]
    jobs = [(view, "base", 0, view) for view in views]
    for name, motion in MOTIONS.items():
        view = "correlator" if name == "correlator-fans" else "radio-dish"
        jobs.extend((view, "motion", frame, name) for frame in range(motion["frames"]))
    cpus = len(os.sched_getaffinity(0))
    workers = min(len(jobs), args.jobs or max(1, cpus // 12))
    threads = args.threads or min(24, max(1, 2 * cpus // workers))
    stage = Path(tempfile.mkdtemp(prefix="render-", dir=OUT))
    print(
        f"Rendering {len(jobs)} poses with {workers} workers × {threads} threads",
        flush=True,
    )

    def render(job):
        view, layer, frame, variant = job
        target = stage / f"{variant}-{layer}-{frame:02d}"
        target.mkdir()
        started = time.monotonic()
        with (target / "blender.log").open("w") as log:
            subprocess.run(
                [
                    args.blender,
                    "--background",
                    "--factory-startup",
                    "--threads",
                    str(threads),
                    "--python-exit-code",
                    "1",
                    "--python",
                    str(ROOT / "art/astronomy/build.py"),
                    "--",
                    "--output",
                    str(target),
                    "--threads",
                    str(threads),
                    "--views",
                    view,
                    "--frame",
                    str(frame),
                    "--layer",
                    layer,
                ],
                check=True,
                stdout=log,
                stderr=subprocess.STDOUT,
                env={**os.environ, "OMP_NUM_THREADS": str(threads)},
            )
        return time.monotonic() - started

    started = time.monotonic()
    with ThreadPoolExecutor(max_workers=workers) as executor:
        timings = dict(
            zip(
                (f"{variant}-{layer}-{frame}" for _, layer, frame, variant in jobs),
                executor.map(render, jobs),
            )
        )
    elapsed = time.monotonic() - started
    metadata = json.loads((stage / f"{views[0]}-base-00" / "render.json").read_text())
    metadata["models"] = {}
    with (OUT / "blender.log").open("w") as log:
        for view, layer, frame, variant in jobs:
            target = stage / f"{variant}-{layer}-{frame:02d}"
            if layer == "base":
                metadata["models"].update(
                    json.loads((target / "render.json").read_text())["models"]
                )
            suffixes = (
                (".blend", "-body.png", "-shadow.png", "-glow.png")
                if layer == "base"
                else ("-body.png",)
            )
            for suffix in suffixes:
                destination = (
                    variant + (f"-frame-{frame:02d}" if frame else "") + suffix
                )
                shutil.copyfile(target / (view + suffix), OUT / destination)
            log.write(f"View: {view}\n" + (target / "blender.log").read_text())
    metadata["motions"] = MOTIONS
    (OUT / "render.json").write_text(json.dumps(metadata, indent=2) + "\n")
    (OUT / "render-timing.json").write_text(
        json.dumps(
            {
                "render_seconds": elapsed,
                "available_cpus": cpus,
                "workers": workers,
                "threads_per_worker": threads,
                "view_seconds": timings,
                "logs": str(stage.relative_to(ROOT)),
            },
            indent=2,
        )
        + "\n"
    )
    publish()
    print(f"Render wall time: {elapsed:.1f}s; logs: {stage}")


if __name__ == "__main__":
    main()
